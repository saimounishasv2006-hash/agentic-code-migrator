"use client";

import { useState } from "react";
import { useRouter } from "next/navigation";
import { motion } from "framer-motion";
import JSZip from "jszip";
import {
  ArrowLeft,
  Check,
  Copy,
  Download,
  FileText,
  GitBranch,
} from "lucide-react";
import { useMigrationStore } from "@/store/migrationStore";

/**
 * Displays export and finalization options for the migration workflow.
 */
export default function ExportPage() {
  const router = useRouter();
  const { files, migrationGoal, analysisResult, migrationPlan } =
    useMigrationStore();
  const [rewrittenFiles] = useState<Map<string, string>>(() => {
    if (typeof window === "undefined") {
      return new Map();
    }

    const storedFiles = window.sessionStorage.getItem("rewrittenFiles");
    if (!storedFiles) {
      return new Map();
    }

    try {
      const parsed = JSON.parse(storedFiles) as Record<string, string>;
      return new Map(Object.entries(parsed));
    } catch {
      return new Map();
    }
  });
  const [copied, setCopied] = useState(false);

  const generateReadme = () => `# Migration Report

## Summary
- Migration Goal: ${migrationGoal}
- Files Migrated: ${files.length}
- Total Complexity: ${analysisResult?.overallComplexity ?? "N/A"}
- Estimated Effort: ${analysisResult?.estimatedEffort ?? "N/A"}

## Patterns Detected
${analysisResult?.codePatterns.map((pattern) => `- ${pattern}`).join("\n") || "None"}

## Migration Plan
${
  migrationPlan?.steps
    .map(
      (step) =>
        `\n### Step ${step.stepNumber}: ${step.title}\n${step.description}`,
    )
    .join("\n") || "No plan generated"
}

## Files Changed
${files.map((file) => `- ${file.name}`).join("\n")}

---
Generated by CodeShift - AI-powered code migration
`;

  const generateGitignore = () => `# Dependencies
node_modules/
.pnp
.pnp.js

# Testing
coverage/

# Build
dist/
build/
.next/
out/

# Misc
.DS_Store
*.pem

# Debug
npm-debug.log*
yarn-debug.log*
yarn-error.log*

# Local env files
.env
.env.local
.env.*.local

# IDE
.vscode/
.idea/
*.swp
*.swo
`;

  const downloadZip = async () => {
    const zip = new JSZip();

    rewrittenFiles.forEach((content, fileName) => {
      zip.file(fileName, content);
    });

    zip.file("MIGRATION_REPORT.md", generateReadme());
    zip.file(".gitignore", generateGitignore());

    const blob = await zip.generateAsync({ type: "blob" });
    const url = URL.createObjectURL(blob);
    const link = document.createElement("a");

    link.href = url;
    link.download = "migrated-code.zip";
    document.body.appendChild(link);
    link.click();
    document.body.removeChild(link);
    URL.revokeObjectURL(url);
  };

  const copyReadme = async () => {
    await navigator.clipboard.writeText(generateReadme());
    setCopied(true);
    window.setTimeout(() => setCopied(false), 2000);
  };

  return (
    <main className="min-h-screen bg-gradient-to-b from-bg via-bg to-surface/30 px-6 py-8">
      <div className="mx-auto max-w-4xl">
        <motion.div
          initial={{ opacity: 0, y: -20 }}
          animate={{ opacity: 1, y: 0 }}
          className="mb-8"
        >
          <button
            onClick={() => router.push("/migrate/validate")}
            className="mb-6 flex items-center gap-2 text-text-dim transition-colors hover:text-accent"
          >
            <ArrowLeft size={16} />
            Back
          </button>

          <div>
            <h1 className="mb-2 text-3xl font-bold text-text">
              Export and Finalize
            </h1>
            <p className="text-text-dim">
              Download your migrated code and documentation.
            </p>
          </div>
        </motion.div>

        <div className="space-y-6">
          <motion.div
            initial={{ opacity: 0, y: 20 }}
            animate={{ opacity: 1, y: 0 }}
            className="rounded-xl border border-border bg-surface/60 p-8 text-center backdrop-blur"
          >
            <Download size={40} className="mx-auto mb-4 text-accent" />
            <h2 className="mb-2 text-xl font-semibold text-text">
              Download Migrated Code
            </h2>
            <p className="mb-6 text-sm text-text-dim">
              All {rewrittenFiles.size} files, the README, and the .gitignore
              file.
            </p>
            <motion.button
              onClick={downloadZip}
              whileHover={{ scale: 1.05 }}
              whileTap={{ scale: 0.95 }}
              className="inline-flex items-center gap-2 rounded-lg bg-accent px-8 py-4 font-semibold text-white transition-colors hover:bg-accent-dim"
            >
              <Download size={16} />
              Download as ZIP
            </motion.button>
          </motion.div>

          <motion.div
            initial={{ opacity: 0, y: 20 }}
            animate={{ opacity: 1, y: 0 }}
            transition={{ delay: 0.1 }}
            className="rounded-xl border border-border bg-surface/60 p-6 backdrop-blur"
          >
            <div className="mb-4 flex items-center gap-2">
              <FileText size={20} className="text-accent" />
              <h3 className="text-lg font-semibold text-text">
                Migration Report
              </h3>
            </div>
            <pre className="mb-4 max-h-96 overflow-y-auto overflow-x-auto rounded-lg bg-bg/60 p-4 font-mono text-sm text-text-dim">
              {generateReadme()}
            </pre>
            <motion.button
              onClick={copyReadme}
              whileHover={{ scale: 1.05 }}
              whileTap={{ scale: 0.95 }}
              className="inline-flex items-center gap-2 rounded-lg border border-border px-4 py-2 text-text transition-colors hover:border-accent hover:text-accent"
            >
              {copied ? (
                <>
                  <Check size={16} />
                  Copied
                </>
              ) : (
                <>
                  <Copy size={16} />
                  Copy Text
                </>
              )}
            </motion.button>
          </motion.div>

          <motion.div
            initial={{ opacity: 0, y: 20 }}
            animate={{ opacity: 1, y: 0 }}
            transition={{ delay: 0.2 }}
            className="rounded-xl border border-border bg-surface/60 p-6 backdrop-blur"
          >
            <div className="mb-4 flex items-center gap-2">
              <GitBranch size={20} className="text-accent" />
              <h3 className="text-lg font-semibold text-text">
                Next Steps for GitHub
              </h3>
            </div>
            <ol className="space-y-3 text-sm text-text-dim">
              <li className="flex gap-3">
                <span className="flex-shrink-0 font-semibold text-accent">
                  1.
                </span>
                <span>Extract the ZIP file to your project folder.</span>
              </li>
              <li className="flex gap-3">
                <span className="flex-shrink-0 font-semibold text-accent">
                  2.
                </span>
                <span>
                  Review the migrated files and check MIGRATION_REPORT.md.
                </span>
              </li>
              <li className="flex gap-3">
                <span className="flex-shrink-0 font-semibold text-accent">
                  3.
                </span>
                <span>
                  Create a new branch:{" "}
                  <span className="rounded bg-bg/60 px-2 py-1 font-mono text-xs">
                    git checkout -b migration
                  </span>
                </span>
              </li>
              <li className="flex gap-3">
                <span className="flex-shrink-0 font-semibold text-accent">
                  4.
                </span>
                <span>
                  Commit changes:{" "}
                  <span className="rounded bg-bg/60 px-2 py-1 font-mono text-xs">
                    git add .; git commit -m &apos;chore: automated
                    migration&apos;
                  </span>
                </span>
              </li>
              <li className="flex gap-3">
                <span className="flex-shrink-0 font-semibold text-accent">
                  5.
                </span>
                <span>Push and create a pull request for review.</span>
              </li>
            </ol>
          </motion.div>

          <motion.div
            initial={{ opacity: 0 }}
            animate={{ opacity: 1 }}
            transition={{ delay: 0.3 }}
          >
            <motion.button
              onClick={() => router.push("/")}
              whileHover={{ scale: 1.05 }}
              whileTap={{ scale: 0.95 }}
              className="w-full rounded-lg bg-accent px-6 py-4 font-semibold text-white transition-colors hover:bg-accent-dim"
            >
              Done. Back to Home
            </motion.button>
          </motion.div>
        </div>
      </div>
    </main>
  );
}
